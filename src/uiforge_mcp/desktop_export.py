"""Native C# / .NET (WPF, Avalonia, WinUI 3) and C++ (Qt 6 QML, Dear ImGui) desktop UI exporters.

Emits clean, idiomatic, dependency-free source files wired to canvas data bindings, click/navigation
interactions, native text labels, native Input fields (TextBox / PasswordBox / TextField / InputText)
and native Scroll containers (ScrollViewer / ScrollView / BeginChild), alongside high-DPI PNG slices
for PBR, shader or filigree graphic groups.
"""

from __future__ import annotations

import html
import re
from pathlib import Path
from typing import Any

from .colors import parse_color
from .widgets import widget_colors_summary

DESKTOP_ENGINES = ("wpf", "avalonia", "winui", "qt-qml", "imgui")


def _pascal(name: str) -> str:
    out = re.sub(r"[^0-9a-zA-Z]+", " ", str(name)).title().replace(" ", "") or "Screen"
    return out if out[0].isalpha() else "Screen" + out


def _ident(name: str) -> str:
    s = re.sub(r"[^0-9a-zA-Z_]+", "_", str(name)).strip("_") or "item"
    return s if s[0].isalpha() or s[0] == "_" else "n_" + s


def _hex_argb(rgba: tuple[int, int, int, int]) -> str:
    r, g, b, a = rgba
    return f"#{a:02X}{r:02X}{g:02X}{b:02X}"


def _hex_rgb(rgba: tuple[int, int, int, int]) -> str:
    r, g, b, _ = rgba
    return f"#{r:02X}{g:02X}{b:02X}"


def _first_rgba(value: Any, colors: dict, fallback: tuple[int, int, int, int] = (255, 255, 255, 255)) -> tuple[int, int, int, int]:
    if not value:
        return fallback
    if isinstance(value, dict):
        stops = value.get("stops") or value.get("colors") or []
        if stops:
            s0 = stops[0]
            value = s0[1] if isinstance(s0, (list, tuple)) and len(s0) == 2 else s0
        else:
            return fallback
    if isinstance(value, str):
        try:
            return parse_color(value, colors)
        except ValueError:
            return fallback
    return fallback


def _xaml_weight(weight: Any) -> str:
    w = int(round(int(weight or 400) / 100.0) * 100)
    return {
        100: "Thin", 200: "ExtraLight", 300: "Light", 400: "Normal",
        500: "Medium", 600: "SemiBold", 700: "Bold", 800: "ExtraBold", 900: "Black",
    }.get(w, "Normal")


def _xaml_align(align: str) -> str:
    return {"left": "Left", "center": "Center", "right": "Right"}.get(str(align).lower(), "Left")


def _collect_bindings(c: dict, nodes: list[dict]) -> dict[str, Any]:
    props: dict[str, Any] = dict(c.get("data") or {})
    for n in nodes:
        if n["kind"] == "input":
            el = n["el"]
            bkey = el.get("bind") or _ident(n["id"])
            if bkey not in props:
                props[bkey] = str(el.get("value") or "")
    return props


def _write_dotnet_viewmodel(c: dict, nodes: list[dict], folder: Path, cls: str, ns: str) -> Path:
    props = _collect_bindings(c, nodes)
    ix = [r for r in (c.get("interactions") or []) if r.get("trigger") == "click"]
    lines = [
        f"// {cls}ViewModel.cs - generated by uiforge-mcp from canvas '{c['id']}'",
        "// Compatible with .NET Framework 4.8 and .NET 8 / 9 (zero external NuGet dependencies).",
        "using System;",
        "using System.ComponentModel;",
        "using System.Runtime.CompilerServices;",
        "using System.Windows.Input;",
        "",
        f"namespace {ns}",
        "{",
        f"    public class {cls}ViewModel : INotifyPropertyChanged",
        "    {",
        "        public event PropertyChangedEventHandler PropertyChanged;",
        "#pragma warning disable CS0067",
        "        public event Action<string, string> NavigateRequested;",
        "        public event Action<string> SfxRequested;",
        "        public event Action<string, bool> StateChanged;",
        "#pragma warning restore CS0067",
        "",
        "        protected void OnPropertyChanged([CallerMemberName] string name = null)",
        "            => PropertyChanged?.Invoke(this, new PropertyChangedEventArgs(name));",
        "",
    ]
    for k, v in props.items():
        pname = _pascal(k)
        fname = "_" + _ident(k)
        if isinstance(v, bool):
            ctype, lit = "bool", ("true" if v else "false")
        elif isinstance(v, (int, float)):
            ctype, lit = "double", f"{float(v):g}"
        else:
            esc = str(v).replace("\\", "\\\\").replace('"', '\\"')
            ctype, lit = "string", f'"{esc}"'
        lines += [
            f"        private {ctype} {fname} = {lit};",
            f"        public {ctype} {pname}",
            "        {",
            f"            get => {fname};",
            f"            set {{ if (!Equals({fname}, value)) {{ {fname} = value; OnPropertyChanged(); }} }}",
            "        }",
            "",
        ]
    for idx, rule in enumerate(ix):
        cmd_name = _pascal(rule["id"].replace("group:", "")) + f"Command"
        if idx > 0 and any(f"public ICommand {cmd_name} " in ln for ln in lines):
            cmd_name = f"{cmd_name}{idx}"
        sfx = f'SfxRequested?.Invoke("{rule["sfx"]}"); ' if rule.get("sfx") else ""
        act = rule.get("action", "")
        if act in ("navigate", "overlay", "back", "url"):
            tgt = str(rule.get("target", "back")).replace('"', '\\"')
            body = f'{sfx}NavigateRequested?.Invoke("{tgt}", "{act}");'
        elif act in ("set_state", "clear_state", "toggle_state"):
            st_n = str(rule.get("state", "")).replace('"', '\\"')
            val = "false" if act == "clear_state" else "true"
            body = f'{sfx}StateChanged?.Invoke("{st_n}", {val});'
        else:
            body = f"{sfx}"
        lines.append(f"        public ICommand {cmd_name} => new RelayCommand(() => {{ {body} }});")
    lines += [
        "",
        "        private sealed class RelayCommand : ICommand",
        "        {",
        "            private readonly Action _run;",
        "            public RelayCommand(Action run) => _run = run;",
        "            public event EventHandler CanExecuteChanged { add { } remove { } }",
        "            public bool CanExecute(object parameter) => true;",
        "            public void Execute(object parameter) => _run();",
        "        }",
        "    }",
        "}",
    ]
    out = folder / f"{cls}ViewModel.cs"
    out.write_text("\n".join(lines) + "\n", encoding="utf-8")
    return out


def _xaml_items(el: dict, colors: dict, dialect: str) -> list[str]:
    items = el.get("items") or []
    gap = float(el.get("gap", 8))
    pad = float(el.get("padding", 10))
    row_h = float(el.get("item_height", 38))
    ifill = _hex_argb(_first_rgba(el.get("item_fill", "#1e293b@0.75"), colors))
    itxt = _hex_argb(_first_rgba(el.get("item_color", "#e2e8f0"), colors))
    isub = _hex_argb(_first_rgba(el.get("subtitle_color", "#94a3b8"), colors))
    fsize = float(el.get("size", 13))
    orient = "Horizontal" if str(el.get("direction", "vertical")).lower() == "horizontal" else "Vertical"
    spacing_attr = f' Spacing="{gap:g}"' if dialect in ("avalonia", "winui") else ""
    out = [f'                <StackPanel Orientation="{orient}" Margin="{pad:g}"{spacing_attr}>']
    for i, raw in enumerate(items):
        if isinstance(raw, dict):
            title = str(raw.get("title") or raw.get("label") or raw.get("text") or f"Item {i + 1}")
            sub = str(raw.get("subtitle") or "")
            badge = str(raw.get("badge") or "")
        else:
            title, sub, badge = str(raw), "", ""
        m_attr = f' Margin="0,0,0,{gap:g}"' if dialect == "wpf" else ""
        out.append(f'                    <Border Background="{ifill}" CornerRadius="6" MinHeight="{row_h:g}" Padding="10,6"{m_attr}>')
        out.append('                        <DockPanel LastChildFill="True">' if dialect in ("wpf", "avalonia") else '                        <Grid>')
        if badge and dialect in ("wpf", "avalonia"):
            out.append(f'                            <TextBlock DockPanel.Dock="Right" Text="{html.escape(badge, quote=True)}" Foreground="#FF38BDF8" FontWeight="Bold" FontSize="{max(10.0, fsize * 0.85):g}" VerticalAlignment="Center" />')
        out.append('                            <StackPanel VerticalAlignment="Center">')
        out.append(f'                                <TextBlock Text="{html.escape(title, quote=True)}" Foreground="{itxt}" FontSize="{fsize:g}" FontWeight="SemiBold" />')
        if sub:
            out.append(f'                                <TextBlock Text="{html.escape(sub, quote=True)}" Foreground="{isub}" FontSize="{max(10.0, fsize * 0.82):g}" />')
        out.append('                            </StackPanel>')
        out.append('                        </DockPanel>' if dialect in ("wpf", "avalonia") else '                        </Grid>')
        out.append('                    </Border>')
    out.append('                </StackPanel>')
    return out


def _write_xaml(c: dict, nodes: list[dict], folder: Path, base: str, colors: dict, dialect: str) -> list[Path]:
    """Emit WPF (.xaml), Avalonia (.axaml), or WinUI 3 (.xaml) UI + C# code-behind + ViewModel."""
    W, H = float(c["width"]), float(c["height"])
    cls = _pascal(base)
    ns = "UIForge.Views"
    ext = "axaml" if dialect == "avalonia" else "xaml"
    bg_hex = _hex_argb(_first_rgba(c.get("background"), colors, (0, 0, 0, 0)))

    if dialect == "wpf":
        xmlns = (
            f'<UserControl x:Class="{ns}.{cls}"\n'
            '             xmlns="http://schemas.microsoft.com/winfx/2006/xaml/presentation"\n'
            '             xmlns:x="http://schemas.microsoft.com/winfx/2006/xaml"\n'
            f'             Width="{W:g}" Height="{H:g}">'
        )
    elif dialect == "avalonia":
        xmlns = (
            f'<UserControl x:Class="{ns}.{cls}"\n'
            '             xmlns="https://github.com/avaloniaui"\n'
            '             xmlns:x="http://schemas.microsoft.com/winfx/2006/xaml"\n'
            f'             Width="{W:g}" Height="{H:g}">'
        )
    else:
        xmlns = (
            f'<UserControl x:Class="{ns}.{cls}"\n'
            '             xmlns="http://schemas.microsoft.com/winfx/2006/xaml/presentation"\n'
            '             xmlns:x="http://schemas.microsoft.com/winfx/2006/xaml"\n'
            f'             Width="{W:g}" Height="{H:g}">'
        )

    lines = [
        f'<!-- {cls}.{ext} - generated by uiforge-mcp ({dialect.upper()}) from canvas "{c["id"]}" ({int(W)}x{int(H)}) -->',
        xmlns,
        '    <Viewbox Stretch="Uniform">',
        f'        <Canvas Width="{W:g}" Height="{H:g}" Background="{bg_hex}">',
    ]

    for node in nodes:
        x0, y0, x1, y1 = node["box"]
        nw, nh = max(1.0, x1 - x0), max(1.0, y1 - y0)
        xname = _ident(node["id"])
        pos = f'Canvas.Left="{x0:.1f}" Canvas.Top="{y0:.1f}" Width="{nw:.1f}" Height="{nh:.1f}"'

        if node["kind"] == "image":
            src = node["file"]
            lines.append(f'            <Image x:Name="{xname}" {pos} Source="{src}" Stretch="Fill" />')
        elif node["kind"] == "text":
            t = node["info"]
            col = _hex_argb(_first_rgba(t["color"], colors))
            txt_raw = str(t["text"])
            lines.append(
                f'            <TextBlock x:Name="{xname}" {pos} Text="{html.escape(txt_raw, quote=True)}" '
                f'FontFamily="{html.escape(str(t["font"]), quote=True)}" FontSize="{float(t["size"]):g}" '
                f'FontWeight="{_xaml_weight(t.get("weight"))}" Foreground="{col}" '
                f'TextAlignment="{_xaml_align(t.get("align", "left"))}" />'
            )
        elif node["kind"] == "input":
            el = node["el"]
            wc = widget_colors_summary(el, colors)
            bg_c = _hex_argb(wc["bg"])
            bd_c = _hex_argb(wc["border"])
            tx_c = _hex_argb(wc["text"])
            rad = float(el.get("radius", 8) if not isinstance(el.get("radius"), list) else el["radius"][0])
            pad = float(el.get("padding", 12))
            fsize = float(el.get("size", 15))
            itype = str(el.get("input_type", "text")).lower()
            bkey = _pascal(el.get("bind") or xname)
            ph = html.escape(str(el.get("placeholder") or ""), quote=True)
            if el.get("label"):
                lines.append(
                    f'            <TextBlock Canvas.Left="{x0 + 2:.1f}" Canvas.Top="{y0:.1f}" '
                    f'Text="{html.escape(str(el["label"]), quote=True)}" Foreground="#FFCBD5E1" '
                    f'FontSize="{max(11.0, fsize * 0.8):g}" FontWeight="SemiBold" />'
                )
            ey = float(el.get("y", y0))
            eh = float(el.get("height", nh))
            ew = float(el.get("width", nw))
            box_pos = f'Canvas.Left="{x0:.1f}" Canvas.Top="{ey:.1f}" Width="{ew:.1f}" Height="{eh:.1f}"'
            if itype == "password" and dialect in ("wpf", "winui"):
                ph_attr = f' PlaceholderText="{ph}"' if dialect == "winui" and ph else ""
                lines += [
                    f'            <Border {box_pos} Background="{bg_c}" BorderBrush="{bd_c}" BorderThickness="{wc["border_width"]:g}" CornerRadius="{rad:g}">',
                    f'                <PasswordBox x:Name="{xname}" Background="Transparent" BorderThickness="0" Foreground="{tx_c}" FontSize="{fsize:g}" Padding="{pad:g},0" VerticalContentAlignment="Center"{ph_attr} />',
                    '            </Border>',
                ]
            else:
                extra_ph = (f' Watermark="{ph}"' if dialect == "avalonia" else
                            f' PlaceholderText="{ph}"' if dialect == "winui" else
                            f' ToolTip="{ph}"') if ph else ""
                pw_attr = ' PasswordChar="•"' if (itype == "password" and dialect == "avalonia") else ""
                bind_attr = f' Text="{{Binding {bkey}, Mode=TwoWay, UpdateSourceTrigger=PropertyChanged}}"' if dialect != "winui" else f' Text="{{x:Bind ViewModel.{bkey}, Mode=TwoWay}}"'
                ro_attr = ' IsReadOnly="True"' if el.get("readonly") else ""
                lines += [
                    f'            <Border {box_pos} Background="{bg_c}" BorderBrush="{bd_c}" BorderThickness="{wc["border_width"]:g}" CornerRadius="{rad:g}">',
                    f'                <TextBox x:Name="{xname}"{bind_attr} Background="Transparent" BorderThickness="0" Foreground="{tx_c}" FontSize="{fsize:g}" Padding="{pad:g},0" VerticalContentAlignment="Center"{extra_ph}{pw_attr}{ro_attr} />',
                    '            </Border>',
                ]
        elif node["kind"] == "scroll":
            el = node["el"]
            wc = widget_colors_summary(el, colors)
            bg_c = _hex_argb(wc["bg"])
            bd_c = _hex_argb(wc["border"])
            rad = float(el.get("radius", 10) if not isinstance(el.get("radius"), list) else el["radius"][0])
            d = str(el.get("direction", "vertical")).lower()
            vsb = "Disabled" if d == "horizontal" else "Auto"
            hsb = "Auto" if d in ("horizontal", "both") else "Disabled"
            lines += [
                f'            <Border {pos} Background="{bg_c}" BorderBrush="{bd_c}" BorderThickness="{wc["border_width"]:g}" CornerRadius="{rad:g}">',
                f'                <ScrollViewer x:Name="{xname}" VerticalScrollBarVisibility="{vsb}" HorizontalScrollBarVisibility="{hsb}">',
                *_xaml_items(el, colors, dialect),
                '                </ScrollViewer>',
                '            </Border>',
            ]

    lines += [
        '        </Canvas>',
        '    </Viewbox>',
        '</UserControl>',
    ]
    xaml_path = folder / f"{cls}.{ext}"
    xaml_path.write_text("\n".join(lines) + "\n", encoding="utf-8")

    if dialect == "wpf":
        usings = "using System.Windows.Controls;"
        ctx_line = "            DataContext = ViewModel;"
    elif dialect == "avalonia":
        usings = "using Avalonia.Controls;"
        ctx_line = "            DataContext = ViewModel;"
    else:
        usings = "using Microsoft.UI.Xaml.Controls;"
        ctx_line = "            DataContext = ViewModel;"

    cs_lines = [
        f"// {cls}.{ext}.cs - code-behind generated by uiforge-mcp",
        usings,
        "",
        f"namespace {ns}",
        "{",
        f"    public partial class {cls} : UserControl",
        "    {",
        f"        public {cls}ViewModel ViewModel {{ get; }} = new {cls}ViewModel();",
        "",
        f"        public {cls}()",
        "        {",
        "            InitializeComponent();",
        ctx_line,
        "        }",
        "    }",
        "}",
    ]
    cs_path = folder / f"{cls}.{ext}.cs"
    cs_path.write_text("\n".join(cs_lines) + "\n", encoding="utf-8")
    vm_path = _write_dotnet_viewmodel(c, nodes, folder, cls, ns)
    return [xaml_path, cs_path, vm_path]


def _write_qt_qml(c: dict, nodes: list[dict], folder: Path, base: str, colors: dict) -> list[Path]:
    """Emit a C++ Qt 6 Quick (.qml) screen with native TextField, ScrollView, signals and properties."""
    W, H = float(c["width"]), float(c["height"])
    cls = _pascal(base)
    bg_hex = _hex_argb(_first_rgba(c.get("background"), colors, (0, 0, 0, 0)))
    props = _collect_bindings(c, nodes)
    click_ids = {r["id"].replace("group:", ""): r for r in (c.get("interactions") or []) if r.get("trigger") == "click"}

    lines = [
        f"// {cls}.qml - generated by uiforge-mcp (Qt 6 Quick / QML) from canvas '{c['id']}' ({int(W)}x{int(H)})",
        "import QtQuick",
        "import QtQuick.Controls",
        "",
        "Item {",
        f"    id: root",
        f"    width: {W:g}",
        f"    height: {H:g}",
        "",
        "    signal navigateRequested(string target, string mode)",
        "    signal sfxRequested(string eventName)",
        "    signal inputChanged(string key, string value)",
        "",
    ]
    for k, v in props.items():
        ident = _ident(k)
        if isinstance(v, bool):
            lines.append(f"    property bool {ident}: {'true' if v else 'false'}")
        elif isinstance(v, (int, float)):
            lines.append(f"    property real {ident}: {float(v):g}")
        else:
            esc = str(v).replace("\\", "\\\\").replace('"', '\\"')
            lines.append(f'    property string {ident}: "{esc}"')
    lines += [
        "",
        "    Rectangle {",
        "        anchors.fill: parent",
        f'        color: "{bg_hex}"',
        "    }",
        "",
    ]

    for node in nodes:
        x0, y0, x1, y1 = node["box"]
        nw, nh = max(1.0, x1 - x0), max(1.0, y1 - y0)
        qid = _ident(node["id"])
        rule = click_ids.get(node["id"])
        if node["kind"] == "image":
            lines += [
                "    Image {",
                f"        id: {qid}",
                f"        x: {x0:.1f}; y: {y0:.1f}; width: {nw:.1f}; height: {nh:.1f}",
                f'        source: "{node["file"]}"',
                "        fillMode: Image.Stretch",
            ]
            if rule:
                sfx = f'root.sfxRequested("{rule["sfx"]}"); ' if rule.get("sfx") else ""
                tgt = str(rule.get("target", "")).replace('"', '\\"')
                act = str(rule.get("action", "click"))
                lines += [
                    "        MouseArea {",
                    "            anchors.fill: parent",
                    "            cursorShape: Qt.PointingHandCursor",
                    f'            onClicked: {{ {sfx}root.navigateRequested("{tgt}", "{act}") }}',
                    "        }",
                ]
            lines.append("    }")
        elif node["kind"] == "text":
            t = node["info"]
            col = _hex_argb(_first_rgba(t["color"], colors))
            txt = str(t["text"]).replace("\\", "\\\\").replace('"', '\\"').replace("\n", "\\n")
            ha = {"left": "Text.AlignLeft", "center": "Text.AlignHCenter", "right": "Text.AlignRight"}.get(t.get("align", "left"), "Text.AlignLeft")
            lines += [
                "    Text {",
                f"        id: {qid}",
                f"        x: {x0:.1f}; y: {y0:.1f}; width: {nw:.1f}; height: {nh:.1f}",
                f'        text: "{txt}"',
                f'        color: "{col}"',
                f'        font.family: "{t["font"]}"',
                f"        font.pixelSize: {int(round(t['size']))}",
                f"        font.bold: {'true' if int(t.get('weight') or 400) >= 600 else 'false'}",
                f"        horizontalAlignment: {ha}",
                "        verticalAlignment: Text.AlignVCenter",
                "    }",
            ]
        elif node["kind"] == "input":
            el = node["el"]
            wc = widget_colors_summary(el, colors)
            rad = float(el.get("radius", 8) if not isinstance(el.get("radius"), list) else el["radius"][0])
            ey, ew, eh = float(el.get("y", y0)), float(el.get("width", nw)), float(el.get("height", nh))
            bkey = _ident(el.get("bind") or qid)
            ph = str(el.get("placeholder") or "").replace("\\", "\\\\").replace('"', '\\"')
            pw_line = "        echoMode: TextInput.Password" if str(el.get("input_type", "")).lower() == "password" else ""
            lines += [
                "    TextField {",
                f"        id: {qid}",
                f"        x: {x0:.1f}; y: {ey:.1f}; width: {ew:.1f}; height: {eh:.1f}",
                f"        text: root.{bkey}",
                f'        placeholderText: "{ph}"',
                f'        color: "{_hex_argb(wc["text"])}"',
                f'        placeholderTextColor: "{_hex_argb(wc["placeholder"])}"',
                f"        font.pixelSize: {int(round(float(el.get('size', 15))))}",
                f"        leftPadding: {float(el.get('padding', 12)):g}",
                f"        readOnly: {'true' if el.get('readonly') else 'false'}",
            ]
            if pw_line:
                lines.append(pw_line)
            lines += [
                f'        onTextEdited: {{ root.{bkey} = text; root.inputChanged("{bkey}", text) }}',
                "        background: Rectangle {",
                f"            radius: {rad:g}",
                f'            color: "{_hex_argb(wc["bg"])}"',
                f'            border.color: "{_hex_argb(wc["border"])}"',
                f'            border.width: {wc["border_width"]:g}',
                "        }",
                "    }",
            ]
        elif node["kind"] == "scroll":
            el = node["el"]
            wc = widget_colors_summary(el, colors)
            rad = float(el.get("radius", 10) if not isinstance(el.get("radius"), list) else el["radius"][0])
            pad, gap = float(el.get("padding", 10)), float(el.get("gap", 8))
            row_h = float(el.get("item_height", 38))
            ifill = _hex_argb(_first_rgba(el.get("item_fill", "#1e293b@0.75"), colors))
            itxt = _hex_argb(_first_rgba(el.get("item_color", "#e2e8f0"), colors))
            layout_cls = "Row" if str(el.get("direction", "vertical")).lower() == "horizontal" else "Column"
            lines += [
                "    Rectangle {",
                f"        x: {x0:.1f}; y: {y0:.1f}; width: {nw:.1f}; height: {nh:.1f}",
                f"        radius: {rad:g}",
                f'        color: "{_hex_argb(wc["bg"])}"',
                f'        border.color: "{_hex_argb(wc["border"])}"',
                f'        border.width: {wc["border_width"]:g}',
                "        clip: true",
                "        ScrollView {",
                f"            id: {qid}",
                f"            anchors.fill: parent; anchors.margins: {pad:g}",
                f"            {layout_cls} {{",
                f"                spacing: {gap:g}",
            ]
            for i, raw in enumerate(el.get("items") or []):
                title = (raw.get("title") or raw.get("label") or f"Item {i + 1}") if isinstance(raw, dict) else str(raw)
                esc_t = str(title).replace("\\", "\\\\").replace('"', '\\"')
                lines += [
                    f'                Rectangle {{ width: {max(40.0, nw - pad * 2 - 14):.1f}; height: {row_h:g}; radius: 6; color: "{ifill}"',
                    f'                    Text {{ anchors.verticalCenter: parent.verticalCenter; x: 10; text: "{esc_t}"; color: "{itxt}"; font.pixelSize: {int(round(float(el.get("size", 13))))} }}',
                    "                }",
                ]
            lines += [
                "            }",
                "        }",
                "    }",
            ]

    lines.append("}")
    out = folder / f"{cls}.qml"
    out.write_text("\n".join(lines) + "\n", encoding="utf-8")
    return [out]


def _imgui_col(rgba: tuple[int, int, int, int]) -> str:
    return f"ImVec4({rgba[0]/255:.3f}f, {rgba[1]/255:.3f}f, {rgba[2]/255:.3f}f, {rgba[3]/255:.3f}f)"


def _write_imgui(c: dict, nodes: list[dict], folder: Path, base: str, colors: dict) -> list[Path]:
    """Emit a self-contained C++17 Dear ImGui header (.hpp) with state struct, InputText & BeginChild scroll."""
    W, H = float(c["width"]), float(c["height"])
    cls = _pascal(base)
    bg_rgba = _first_rgba(c.get("background"), colors, (15, 23, 42, 255))
    props = _collect_bindings(c, nodes)
    click_ids = {r["id"].replace("group:", ""): r for r in (c.get("interactions") or []) if r.get("trigger") == "click"}

    lines = [
        f"// {base}_ui.hpp - generated by uiforge-mcp (C++ Dear ImGui) from canvas '{c['id']}' ({int(W)}x{int(H)})",
        "#pragma once",
        '#include "imgui.h"',
        "#include <functional>",
        "#include <string>",
        "",
        "namespace UIForge {",
        "",
        f"struct {cls}State {{",
    ]
    for k, v in props.items():
        ident = _ident(k)
        if isinstance(v, bool):
            lines.append(f"    bool {ident} = {'true' if v else 'false'};")
        elif isinstance(v, (int, float)):
            lines.append(f"    float {ident} = {float(v):g}f;")
        else:
            esc = str(v).replace("\\", "\\\\").replace('"', '\\"')
            lines.append(f'    char {ident}[256] = "{esc}";')
    lines += [
        "    std::function<void(const char*, const char*)> onNavigate;",
        "    std::function<void(const char*)> onSfx;",
        "};",
        "",
        f"inline void Draw{cls}({cls}State& state, const char* title = \"{cls}\") {{",
        f"    ImGui::SetNextWindowSize(ImVec2({W:g}f, {H:g}f), ImGuiCond_FirstUseEver);",
        f"    ImGui::PushStyleColor(ImGuiCol_WindowBg, {_imgui_col(bg_rgba)});",
        "    if (ImGui::Begin(title, nullptr, ImGuiWindowFlags_NoScrollbar)) {",
    ]

    for node in nodes:
        x0, y0, x1, y1 = node["box"]
        nw, nh = max(1.0, x1 - x0), max(1.0, y1 - y0)
        nid = node["id"]
        rule = click_ids.get(nid)
        if node["kind"] == "image":
            lines.append(f"        ImGui::SetCursorPos(ImVec2({x0:.1f}f, {y0:.1f}f));")
            if rule:
                sfx = f'if (state.onSfx) state.onSfx("{rule["sfx"]}"); ' if rule.get("sfx") else ""
                tgt = str(rule.get("target", "")).replace('"', '\\"')
                act = str(rule.get("action", "click"))
                lines.append(f'        if (ImGui::Button("##{nid}", ImVec2({nw:.1f}f, {nh:.1f}f))) {{ {sfx}if (state.onNavigate) state.onNavigate("{tgt}", "{act}"); }}')
            else:
                lines.append(f'        ImGui::Dummy(ImVec2({nw:.1f}f, {nh:.1f}f)); // Draw texture "{node["file"]}" via ImGui::Image')
        elif node["kind"] == "text":
            t = node["info"]
            col = _first_rgba(t["color"], colors)
            txt = str(t["text"]).replace("\\", "\\\\").replace('"', '\\"').replace("\n", "\\n")
            lines += [
                f"        ImGui::SetCursorPos(ImVec2({x0:.1f}f, {y0:.1f}f));",
                f'        ImGui::TextColored({_imgui_col(col)}, "%s", "{txt}");',
            ]
        elif node["kind"] == "input":
            el = node["el"]
            wc = widget_colors_summary(el, colors)
            ey, ew = float(el.get("y", y0)), float(el.get("width", nw))
            bkey = _ident(el.get("bind") or nid)
            ph = str(el.get("placeholder") or "").replace("\\", "\\\\").replace('"', '\\"')
            flags = ["ImGuiInputTextFlags_None"]
            if str(el.get("input_type", "")).lower() == "password":
                flags.append("ImGuiInputTextFlags_Password")
            if el.get("readonly"):
                flags.append("ImGuiInputTextFlags_ReadOnly")
            rad = float(el.get("radius", 8) if not isinstance(el.get("radius"), list) else el["radius"][0])
            lines += [
                f"        ImGui::SetCursorPos(ImVec2({x0:.1f}f, {ey:.1f}f));",
                f"        ImGui::PushItemWidth({ew:.1f}f);",
                f"        ImGui::PushStyleVar(ImGuiStyleVar_FrameRounding, {rad:g}f);",
                f"        ImGui::PushStyleColor(ImGuiCol_FrameBg, {_imgui_col(wc['bg'])});",
                f"        ImGui::PushStyleColor(ImGuiCol_Text, {_imgui_col(wc['text'])});",
                f'        ImGui::InputTextWithHint("##{nid}", "{ph}", state.{bkey}, sizeof(state.{bkey}), {" | ".join(flags)});',
                "        ImGui::PopStyleColor(2);",
                "        ImGui::PopStyleVar();",
                "        ImGui::PopItemWidth();",
            ]
        elif node["kind"] == "scroll":
            el = node["el"]
            wc = widget_colors_summary(el, colors)
            rad = float(el.get("radius", 10) if not isinstance(el.get("radius"), list) else el["radius"][0])
            flags = "ImGuiWindowFlags_HorizontalScrollbar" if str(el.get("direction", "vertical")).lower() in ("horizontal", "both") else "0"
            lines += [
                f"        ImGui::SetCursorPos(ImVec2({x0:.1f}f, {y0:.1f}f));",
                f"        ImGui::PushStyleVar(ImGuiStyleVar_ChildRounding, {rad:g}f);",
                f"        ImGui::PushStyleColor(ImGuiCol_ChildBg, {_imgui_col(wc['bg'])});",
                f'        if (ImGui::BeginChild("##{nid}", ImVec2({nw:.1f}f, {nh:.1f}f), true, {flags})) {{',
            ]
            for i, raw in enumerate(el.get("items") or []):
                title = (raw.get("title") or raw.get("label") or f"Item {i + 1}") if isinstance(raw, dict) else str(raw)
                esc_t = str(title).replace("\\", "\\\\").replace('"', '\\"')
                lines.append(f'            ImGui::Selectable("{esc_t}##{nid}_{i}");')
            lines += [
                "        }",
                "        ImGui::EndChild();",
                "        ImGui::PopStyleColor();",
                "        ImGui::PopStyleVar();",
            ]

    lines += [
        "    }",
        "    ImGui::End();",
        "    ImGui::PopStyleColor();",
        "}",
        "",
        "} // namespace UIForge",
    ]
    out = folder / f"{base}_ui.hpp"
    out.write_text("\n".join(lines) + "\n", encoding="utf-8")
    return [out]


def write_desktop(engine: str, c: dict, nodes: list[dict], folder: Path, base: str, colors: dict) -> tuple[list[Path], str]:
    """Dispatch a desktop engine export and return (written_paths, next_step_hint)."""
    eng = engine.lower()
    cls = _pascal(base)
    if eng == "wpf":
        return (_write_xaml(c, nodes, folder, base, colors, "wpf"),
                f"Add {cls}.xaml, {cls}.xaml.cs and {cls}ViewModel.cs (plus PNGs as Content) to your C# WPF (.NET 8/9 or .NET Framework 4.8) project.")
    if eng == "avalonia":
        return (_write_xaml(c, nodes, folder, base, colors, "avalonia"),
                f"Add {cls}.axaml, {cls}.axaml.cs and {cls}ViewModel.cs to your cross-platform .NET Avalonia UI project.")
    if eng == "winui":
        return (_write_xaml(c, nodes, folder, base, colors, "winui"),
                f"Add {cls}.xaml, {cls}.xaml.cs and {cls}ViewModel.cs to your Windows App SDK / WinUI 3 project.")
    if eng == "qt-qml":
        return (_write_qt_qml(c, nodes, folder, base, colors),
                f"Load {cls}.qml in your C++ Qt 6 QQmlApplicationEngine with the exported PNG assets alongside it.")
    if eng == "imgui":
        return (_write_imgui(c, nodes, folder, base, colors),
                f"Include {base}_ui.hpp in your C++ Dear ImGui app and call UIForge::Draw{cls}(state); inside your render loop.")
    raise ValueError(f"Unsupported desktop engine '{engine}'")
