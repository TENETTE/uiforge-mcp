from __future__ import annotations

UNITY_IMPORTER = r'''// UiForgeImporter.cs  -  generated by uiforge-mcp
// Put this file in any folder named "Editor" (e.g. Assets/Editor/UiForgeImporter.cs).
// Every PNG that has a "<name>.uiforge.json" file next to it is imported as a UI sprite
// with the right settings and 9-slice border. Change the JSON -> right click the PNG -> Reimport.
#if UNITY_EDITOR
using System.IO;
using UnityEditor;
using UnityEngine;

public class UiForgeImporter : AssetPostprocessor
{
    [System.Serializable]
    private class Sidecar
    {
        public bool has_border;
        public int border_left;
        public int border_bottom;
        public int border_right;
        public int border_top;
        public float pixels_per_unit = 100f;
    }

    private void OnPreprocessTexture()
    {
        string sidecarPath = Path.ChangeExtension(assetPath, ".uiforge.json");
        if (!File.Exists(sidecarPath)) return;

        Sidecar meta = JsonUtility.FromJson<Sidecar>(File.ReadAllText(sidecarPath));
        if (meta == null) return;

        TextureImporter importer = (TextureImporter)assetImporter;
        importer.textureType = TextureImporterType.Sprite;
        importer.spriteImportMode = SpriteImportMode.Single;
        importer.mipmapEnabled = false;
        importer.alphaIsTransparency = true;
        importer.sRGBTexture = true;
        importer.wrapMode = TextureWrapMode.Clamp;
        importer.filterMode = FilterMode.Bilinear;
        importer.textureCompression = TextureImporterCompression.Uncompressed;
        importer.spritePixelsPerUnit = meta.pixels_per_unit > 0f ? meta.pixels_per_unit : 100f;

        TextureImporterSettings settings = new TextureImporterSettings();
        importer.ReadTextureSettings(settings);
        settings.spriteMeshType = SpriteMeshType.FullRect;
        if (meta.has_border)
        {
            // Unity border order: left, bottom, right, top
            settings.spriteBorder = new Vector4(meta.border_left, meta.border_bottom, meta.border_right, meta.border_top);
        }
        importer.SetTextureSettings(settings);
    }
}
#endif
'''

UNREAL_IMPORT = r'''# import_uiforge.py  -  generated by uiforge-mcp
# Run inside the Unreal Editor (Python Editor Script Plugin enabled):
#   Output Log -> switch "Cmd" to "Python" ->  py "C:/path/to/import_uiforge.py"
# It imports every PNG listed in uiforge_manifest.json with UI texture settings and
# prints the Margin to type into each brush (Draw As = Box) for 9-slice assets.
import json
import os

import unreal

SOURCE_DIR = os.path.dirname(os.path.abspath(__file__))
DEST_PATH = "__DEST_PATH__"


def import_uiforge(source_dir=SOURCE_DIR, dest_path=DEST_PATH):
    with open(os.path.join(source_dir, "uiforge_manifest.json"), "r", encoding="utf-8") as handle:
        manifest = json.load(handle)

    tasks = []
    info = {}
    for name, entry in manifest.get("assets", {}).items():
        for item in entry.get("files", []):
            filename = os.path.join(source_dir, item["file"])
            if not os.path.isfile(filename):
                unreal.log_warning("uiforge-mcp: missing file " + filename)
                continue
            task = unreal.AssetImportTask()
            task.set_editor_property("filename", filename)
            task.set_editor_property("destination_path", dest_path)
            task.set_editor_property("automated", True)
            task.set_editor_property("replace_existing", True)
            task.set_editor_property("save", True)
            tasks.append(task)
            info[os.path.splitext(item["file"])[0]] = item

    if not tasks:
        unreal.log_warning("uiforge-mcp: nothing to import")
        return

    unreal.AssetToolsHelpers.get_asset_tools().import_asset_tasks(tasks)

    for task in tasks:
        for object_path in task.get_editor_property("imported_object_paths"):
            texture = unreal.load_asset(object_path)
            if not isinstance(texture, unreal.Texture2D):
                continue
            texture.set_editor_property("compression_settings", unreal.TextureCompressionSettings.TC_EDITOR_ICON)
            texture.set_editor_property("lod_group", unreal.TextureGroup.TEXTUREGROUP_UI)
            texture.set_editor_property("mip_gen_settings", unreal.TextureMipGenSettings.TMGS_NO_MIPMAPS)
            texture.set_editor_property("srgb", True)
            texture.set_editor_property("never_stream", True)
            unreal.EditorAssetLibrary.save_loaded_asset(texture)
            item = info.get(texture.get_name())
            margin = (item or {}).get("unreal", {}).get("margin_LTRB")
            if margin:
                unreal.log("uiforge-mcp: {0}  ->  Draw As: Box, Margin L/T/R/B = {1}".format(texture.get_name(), margin))
            else:
                unreal.log("uiforge-mcp: {0}  ->  Draw As: Image".format(texture.get_name()))


import_uiforge()
'''

ROBLOX_MODULE_HEAD = '''--!strict
-- UiForgeAssets  -  generated by uiforge-mcp
-- ModuleScript: put it in ReplicatedStorage. Upload each PNG in Studio (Asset Manager or
-- Creator Hub), then pass the ids to write_engine_helpers(roblox_ids=...) or paste them below.
--
--   local UiForge = require(game.ReplicatedStorage.UiForgeAssets)
--   UiForge.apply(script.Parent.Panel, "panel_main")   -- sets Image, ScaleType, SliceCenter...

export type Asset = {
	id: string,
	size: Vector2,
	slice: Rect?,
	sliceScale: number?,
	rectOffset: Vector2?,
	rectSize: Vector2?,
	hover: string?,
	pressed: string?,
}

local Assets: { [string]: Asset } = {
'''

ROBLOX_MODULE_TAIL = '''}

local UiForge = {}

UiForge.Assets = Assets

function UiForge.apply(image: ImageLabel | ImageButton, name: string)
	local asset = Assets[name]
	assert(asset, "UiForge: unknown asset " .. name)
	image.Image = asset.id
	image.BackgroundTransparency = 1
	if asset.rectSize then
		image.ImageRectOffset = asset.rectOffset or Vector2.zero
		image.ImageRectSize = asset.rectSize
	end
	if asset.slice then
		image.ScaleType = Enum.ScaleType.Slice
		image.SliceCenter = asset.slice
		image.SliceScale = asset.sliceScale or 1
	else
		image.ScaleType = Enum.ScaleType.Stretch
	end
	if image:IsA("ImageButton") then
		local hover = asset.hover and Assets[asset.hover]
		local pressed = asset.pressed and Assets[asset.pressed]
		if hover then image.HoverImage = hover.id end
		if pressed then image.PressedImage = pressed.id end
	end
end

return UiForge
'''


def roblox_module(manifest: dict) -> str:
    lines = [ROBLOX_MODULE_HEAD]
    for name in sorted(manifest.get("assets", {})):
        entry = manifest["assets"][name]
        files = entry.get("files") or []
        if not files:
            continue
        item = files[0]
        rb = item.get("roblox", {})
        w, h = rb.get("imageSize", [item.get("width", 0), item.get("height", 0)])
        asset_id = str(entry.get("roblox_id") or "0")
        if asset_id.isdigit():
            asset_id = "rbxassetid://" + asset_id
        fields = [f'id = "{asset_id}"', f"size = Vector2.new({w}, {h})"]
        if rb.get("SliceCenter"):
            a, b, c, d = rb["SliceCenter"]
            fields.append(f"slice = Rect.new({a}, {b}, {c}, {d})")
            fields.append(f"sliceScale = {rb.get('SliceScale', 1)}")
        for sname in ("hover", "pressed"):
            if (entry.get("states") or {}).get(sname):
                fields.append(f'{sname} = "{entry["states"][sname]}"')
        frame = entry.get("atlas_frame")
        if frame:
            fields.append(f"rectOffset = Vector2.new({frame['x']}, {frame['y']})")
            fields.append(f"rectSize = Vector2.new({frame['w']}, {frame['h']})")
        key = name if name.replace("_", "a").isalnum() and not name[0].isdigit() else f'["{name}"]'
        lines.append(f"\t{key} = {{ " + ", ".join(fields) + " },\n")
    lines.append(ROBLOX_MODULE_TAIL)
    return "".join(lines)


def godot_styleboxes(manifest: dict, res_dir: str) -> dict[str, str]:
    """One StyleBoxTexture .tres per 9-sliced asset (Godot 4 text resource format)."""
    res_dir = res_dir.rstrip("/")
    out = {}
    for name, entry in sorted(manifest.get("assets", {}).items()):
        files = entry.get("files") or []
        first = next((f for f in files if f.get("scale", 1) == 1), files[0] if files else None)
        if not first or not first.get("nine_slice"):
            continue
        b = first["nine_slice"]
        out[f"{name}.stylebox.tres"] = (
            '[gd_resource type="StyleBoxTexture" load_steps=2 format=3]\n\n'
            f'[ext_resource type="Texture2D" path="{res_dir}/{first["file"]}" id="1_tex"]\n\n'
            "[resource]\n"
            'texture = ExtResource("1_tex")\n'
            f"texture_margin_left = {float(b['left'])}\n"
            f"texture_margin_top = {float(b['top'])}\n"
            f"texture_margin_right = {float(b['right'])}\n"
            f"texture_margin_bottom = {float(b['bottom'])}\n"
        )
    return out
